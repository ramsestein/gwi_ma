"""
List USB-serial adapters and generate udev rules that give them fixed names.

On Linux, /dev/ttyUSB0, /dev/ttyUSB1... can swap between reboots. A udev rule
per adapter adds a stable alias such as /dev/ttyBIS or /dev/ttyMASIMO. Rules
match the adapter's serial number when it has a unique one, otherwise the
physical USB socket it is plugged into (then it must always go in the same
socket). FTDI adapters also get their latency timer set to 1 ms for better
timestamps.

Usage:
  python -m src.utils.serial_ports
      list adapters
  python -m src.utils.serial_ports --udev BIS=/dev/ttyUSB0 MASIMO=/dev/ttyUSB1 RESEARCH=/dev/ttyUSB2
      print the rules (only the rules go to stdout, so they can be piped):
      ... | sudo tee /etc/udev/rules.d/99-bisbridge.rules
      sudo udevadm control --reload && sudo udevadm trigger
"""
import argparse
import re
import sys
from typing import Dict, List, Optional

from serial.tools import list_ports

FTDI_VID = 0x0403
FTDI_LATENCY_RULE = ('ACTION=="add", SUBSYSTEM=="usb-serial", DRIVER=="ftdi_sio", '
                     'ATTR{latency_timer}="1"')


def list_adapters(ports=None) -> List:
    ports = list(list_ports.comports()) if ports is None else list(ports)
    return [p for p in ports if getattr(p, "vid", None) is not None]


def _unique_serial(port, adapters) -> Optional[str]:
    serial_number = getattr(port, "serial_number", None)
    if not serial_number:
        return None
    same = [a for a in adapters
            if (a.vid, a.pid, getattr(a, "serial_number", None)) == (port.vid, port.pid, serial_number)]
    return serial_number if len(same) == 1 else None


def udev_rule(role: str, port, adapters) -> str:
    if not re.fullmatch(r"[A-Za-z0-9_]+", role):
        raise ValueError(f"Role '{role}' must be letters, digits or _")
    alias = f"tty{role.upper()}"
    serial_number = _unique_serial(port, adapters)
    if serial_number:
        return (f'SUBSYSTEM=="tty", ATTRS{{idVendor}}=="{port.vid:04x}", '
                f'ATTRS{{idProduct}}=="{port.pid:04x}", ATTRS{{serial}}=="{serial_number}", '
                f'SYMLINK+="{alias}"')
    location = getattr(port, "location", None)
    if not location:
        raise ValueError(f"{port.device} has no unique serial number and no USB location")
    return f'SUBSYSTEM=="tty", KERNELS=="{location}", SYMLINK+="{alias}"'


def build_rules(mapping: Dict[str, str], ports=None) -> str:
    adapters = list_adapters(ports)
    by_device = {p.device: p for p in adapters}
    lines = ["# Fixed names for the BIS translator adapters (generated by src.utils.serial_ports)"]
    for role, device in mapping.items():
        if device not in by_device:
            raise ValueError(f"{device} is not a connected USB-serial adapter. "
                             f"Connected: {', '.join(sorted(by_device)) or 'none'}")
        port = by_device[device]
        if not _unique_serial(port, adapters):
            lines.append(f"# {role}: no unique serial number, matched by USB socket "
                         f"{port.location}: always plug it into the same socket")
        lines.append(udev_rule(role, port, adapters))
    if any(by_device[d].vid == FTDI_VID for d in mapping.values()):
        lines.append(FTDI_LATENCY_RULE)
    return "\n".join(lines) + "\n"


def describe(port) -> str:
    serial_number = getattr(port, "serial_number", None) or "-"
    location = getattr(port, "location", None) or "-"
    product = getattr(port, "product", None) or getattr(port, "description", "") or ""
    return (f"{port.device:<14} {port.vid:04x}:{port.pid:04x}  serial={serial_number:<12} "
            f"usb={location:<10} {product}")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="List USB-serial adapters and generate udev rules.")
    parser.add_argument("--udev", nargs="+", metavar="ROLE=DEVICE",
                        help="print udev rules, e.g. BIS=/dev/ttyUSB0 MASIMO=/dev/ttyUSB1")
    args = parser.parse_args(argv)

    if not args.udev:
        adapters = list_adapters()
        if not adapters:
            print("No USB-serial adapters found.")
            return 1
        for port in adapters:
            print(describe(port))
        return 0

    mapping = {}
    for item in args.udev:
        if "=" not in item:
            parser.error(f"'{item}' must be ROLE=DEVICE")
        role, device = item.split("=", 1)
        mapping[role] = device
    try:
        sys.stdout.write(build_rules(mapping))
    except ValueError as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
